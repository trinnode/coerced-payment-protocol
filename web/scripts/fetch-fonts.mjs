// One-shot font fetcher: downloads only the Latin subset as .woff2 and writes
// app/fonts.css. Re-runnable; deterministic output.
//
// Typeface rationale (see docs/design.md):
//   Gloock           display / large statements — high-contrast serif, uncommon in fintech
//   Familjen Grotesk interface / body           — Swedish grotesk, distinctive a/g, variable
//   Azeret Mono      protocol, refs, amounts    — wide mono, uncommon, high legibility
import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";

const OUT = join(process.cwd(), "public", "fonts");
const APP = join(process.cwd(), "app");
const CSS = join(APP, "fonts.css");
const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/121.0 Safari/537.36";

const targets = [
  {
    family: "Gloock",
    slug: "gloock",
    css: "https://fonts.googleapis.com/css2?family=Gloock&display=swap",
  },
  {
    family: "Familjen Grotesk",
    slug: "familjen-grotesk",
    css: "https://fonts.googleapis.com/css2?family=Familjen+Grotesk:wght@400..700&display=swap",
  },
  {
    family: "Azeret Mono",
    slug: "azeret-mono",
    css: "https://fonts.googleapis.com/css2?family=Azeret+Mono:wght@100..900&display=swap",
  },
];

const isLatin = (block) => {
  const m = block.match(/unicode-range:\s*([^;]+);/i);
  return !m || m[1].includes("U+0000-00FF");
};

const faces = [];
await mkdir(OUT, { recursive: true });
await mkdir(APP, { recursive: true });

for (const t of targets) {
  const css = await (await fetch(t.css, { headers: { "User-Agent": UA } })).text();
  const blocks = [...css.matchAll(/@font-face\s*\{[^}]*\}/g)].map((m) => m[0]);
  const picked = new Map();

  for (const b of blocks) {
    if (!isLatin(b)) continue;
    const weight = ((b.match(/font-weight:\s*([\d ]+);/) || [])[1] ?? "400").trim();
    const style = (b.match(/font-style:\s*(\w+)/) || [])[1] ?? "normal";
    const url = (b.match(/url\(['"]?([^'")]+\.woff2)['"]?\)/) || [])[1];
    if (!url) continue;
    picked.set(`${weight}|${style}`, url.startsWith("//") ? `https:${url}` : url);
  }

  for (const [key, url] of picked) {
    const [weight, style] = key.split("|");
    const label = weight.replace(/\s+/g, "-");
    const file = `${t.slug}-${style === "italic" ? "italic-" : ""}${label}.woff2`;
    const res = await fetch(url, { headers: { "User-Agent": UA } });
    if (!res.ok) throw new Error(`${file}: ${res.status}`);
    const buf = Buffer.from(await res.arrayBuffer());
    await writeFile(join(OUT, file), buf);
    faces.push({ family: t.family, weight, style, file, bytes: buf.length });
    console.log(`${file}  ${(buf.length / 1024).toFixed(1)}kB`);
  }
}

const css = faces
  .map(
    (f) => `@font-face {
  font-family: "${f.family}";
  src: url("/fonts/${f.file}") format("woff2");
  font-weight: ${f.weight};
  font-style: ${f.style};
  font-display: swap;
}`,
  )
  .join("\n\n");

await writeFile(CSS, `/* Generated by scripts/fetch-fonts.mjs — do not edit by hand */\n\n${css}\n`);
console.log(`\nwrote ${faces.length} faces → app/fonts.css`);
